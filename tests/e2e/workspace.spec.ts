import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import JSZip from 'jszip';

test('homepage has pre-rendered content and responsive navigation', async ({ page, request }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const response = await request.get('/');
  expect(await response.text()).toContain('Every language.');
  expect(await response.text()).toContain('data-prerendered="true"');
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Every language. All in one place.' })).toBeVisible();
  await expect(page).toHaveTitle(/Locale/);
  await page.screenshot({ path: 'test-results/home-desktop.png', fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('link', { name: 'Open workspace' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/home-mobile.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('link', { name: 'Open workspace' }).click();
  await expect(page.getByRole('heading', { name: 'A fresh start. In every language.' })).toBeVisible();
  expect(errors).toEqual([]);
});

test('creates, imports, edits, persists, filters, and exports a project', async ({ page }) => {
  const errors: string[] = [];
  const external: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (!request.url().startsWith('http://127.0.0.1:4173') && !request.url().startsWith('blob:')) external.push(request.url()); });
  await page.goto('/workspace?new=1');
  await page.getByLabel('Project name').fill('Meter app');
  await page.getByLabel('Description').fill('Our local translation files.');
  await page.getByRole('button', { name: 'Create project', exact: true }).click();
  await page.getByRole('button', { name: 'Import files', exact: true }).click();
  const original = { meters: { smart_meter: 'Smart meter' }, greeting: 'Hello, {{name}}!', list: ['First', 'Second'], enabled: true, count: 12, nil: null, blank: '' };
  await page.getByLabel('Select JSON files').setInputFiles([
    { name: 'common.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(original, null, 2)) },
    { name: 'navigation.json', mimeType: 'application/json', buffer: Buffer.from('{"home":"Home"}') },
  ]);
  await page.getByRole('dialog').getByRole('button', { name: 'Import files', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'en.common.meters.smart_meter', exact: true })).toHaveValue('Smart meter');
  await page.getByRole('textbox', { name: 'en.common.meters.smart_meter', exact: true }).fill('My updated smart meter');
  await page.getByRole('textbox', { name: 'en.common.list[1]', exact: true }).fill('Second, edited');
  await expect(page.getByRole('status').filter({ hasText: 'Saved on this device' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('textbox', { name: 'en.common.meters.smart_meter', exact: true })).toHaveValue('My updated smart meter');
  await page.getByRole('button', { name: 'Add language', exact: true }).click();
  await page.getByRole('button', { name: 'Already have JSON files? Import them' }).click();
  await page.getByLabel('Language / dialect').selectOption('pt-PT');
  await page.getByLabel('Select JSON files').setInputFiles({ name: 'common.json', mimeType: 'application/json', buffer: Buffer.from('{"meters":{"smart_meter":"Contador"}}') });
  await page.getByRole('dialog').getByRole('button', { name: 'Import files', exact: true }).click();
  await page.getByRole('textbox', { name: 'pt-PT.common.greeting', exact: true }).fill('Olá, {{name}}!');
  await page.getByLabel('Search keys or translations').fill('meters.smart_meter');
  await expect(page.locator('tbody tr')).toHaveCount(1);
  await page.getByRole('button', { name: 'Clear search' }).click();
  await page.getByLabel('Filter translations').selectOption('missing');
  await expect(page.getByRole('textbox', { name: 'en.common.meters.smart_meter', exact: true })).toHaveCount(0);
  await page.getByLabel('Filter translations').selectOption('all');
  await page.screenshot({ path: 'test-results/editor-desktop.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Export files', exact: true }).click();
  const singleDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download en/common.json', exact: true }).click();
  const file = await singleDownload;
  expect(file.suggestedFilename()).toBe('common.json');
  expect(JSON.parse(await readFile((await file.path())!, 'utf8'))).toEqual({ ...original, meters: { smart_meter: 'My updated smart meter' }, list: ['First', 'Second, edited'] });
  const allDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: /Download ZIP/ }).click();
  const all = await allDownload;
  const zip = await JSZip.loadAsync(await readFile((await all.path())!));
  expect(Object.values(zip.files).filter(file => !file.dir)).toHaveLength(3);
  expect(JSON.parse(await zip.file('pt-PT/common.json')!.async('string')).greeting).toBe('Olá, {{name}}!');
  await page.getByLabel('What would you like to export?').selectOption('pt-PT');
  const languageDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: /Download ZIP/ }).click();
  const languageZip = await JSZip.loadAsync(await readFile((await (await languageDownload).path())!));
  expect(Object.values(languageZip.files).filter(file => !file.dir).map(file => file.name)).toEqual(['pt-PT/common.json']);
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/editor-mobile.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await page.getByRole('navigation', { name: 'Workspace navigation' }).getByRole('button', { name: 'Languages' }).click();
  await expect(page.getByRole('heading', { name: 'Every language belongs.' })).toBeVisible();
  expect(errors).toEqual([]);
  expect(external).toEqual([]);
});

test('rejects malformed JSON and requires confirmation before replacement', async ({ page }) => {
  await page.goto('/workspace?demo=1');
  await expect(page.getByRole('textbox', { name: 'en.common.welcome.title', exact: true })).toHaveValue('A good place to begin.');
  await page.getByRole('button', { name: 'Import files', exact: true }).click();
  await page.getByLabel('Select JSON files').setInputFiles({ name: 'common.json', mimeType: 'application/json', buffer: Buffer.from('{bad json}') });
  await expect(page.getByRole('alert')).toContainText('invalid JSON');
  await expect(page.getByRole('dialog').getByRole('button', { name: 'Import files', exact: true })).toBeDisabled();
  await page.getByLabel('Select JSON files').setInputFiles({ name: 'common.json', mimeType: 'application/json', buffer: Buffer.from('{"welcome":{"title":"Replacement"}}') });
  await expect(page.getByRole('button', { name: 'Replace & import' })).toBeDisabled();
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Replace & import' }).click();
  await expect(page.getByRole('textbox', { name: 'en.common.welcome.title', exact: true })).toHaveValue('Replacement');
  await page.getByRole('button', { name: 'Project actions' }).click();
  await page.getByRole('menuitem', { name: 'Delete project' }).click();
  await page.getByRole('button', { name: 'Keep it' }).click();
  await expect(page.getByRole('textbox', { name: 'en.common.welcome.title', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Project actions' }).click();
  await page.getByRole('menuitem', { name: 'Delete project' }).click();
  await page.getByRole('button', { name: 'Yes, remove it' }).click();
  await expect(page.getByRole('heading', { name: 'A fresh start. In every language.' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'A fresh start. In every language.' })).toBeVisible();
});
